import { test, expect } from '@playwright/test'
test('注册、创建订单、测试支付、查看权益和退出', async ({ page }) => {
 await page.goto('/')
 await expect(page.getByRole('heading', { name: '连接，从这里开始。' })).toBeVisible()
 await page.getByRole('button', { name: '创建账号 ↗' }).click()
 await page.getByRole('textbox', { name: '邮箱', exact: true }).fill(`browser-${Date.now()}@example.test`)
 await page.getByRole('textbox', { name: '密码', exact: true }).fill('browser-test-password-2026')
 await page.getByRole('button', { name: '创建账号', exact: true }).last().click()
 await expect(page.getByRole('heading', { name: '欢迎回来。' })).toBeVisible()
 await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: /探索套餐/ }).click()
 await page.getByRole('button', { name: /选择 轻量探索/ }).click()
 await expect(page.getByRole('heading', { name: '每一笔，都有记录。' })).toBeVisible()
 await page.getByRole('button', { name: '确认测试支付' }).click()
 await expect(page.getByText('已开通', { exact: true })).toBeVisible()
 await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: /我的概览/ }).click()
 await expect(page.getByRole('heading', { name: '轻量探索', exact: true })).toBeVisible()
 await page.screenshot({ path: 'test-results/dashboard.png', fullPage: true })
 await page.getByRole('button', { name: '退出', exact: true }).click()
 await expect(page.getByRole('heading', { name: '连接，从这里开始。' })).toBeVisible()
})
