import { test, expect } from '@playwright/test'

test('用户生成订阅、重新进入不回显链接，轮换及撤销使旧链接失效', async ({ page }) => {
 const email = `subscription-${Date.now()}@example.test`
 await page.goto('/')
 await page.getByRole('button', { name: '创建账号 ↗' }).click()
 await page.getByRole('textbox', { name: '邮箱', exact: true }).fill(email)
 await page.getByRole('textbox', { name: '密码', exact: true }).fill('subscription-browser-password')
 await page.getByRole('button', { name: '创建账号', exact: true }).last().click()
 await expect(page.getByRole('heading', { name: '欢迎回来。' })).toBeVisible()
 const navigation = page.getByRole('navigation', { name: '主导航' })
 await navigation.getByRole('button', { name: /我的订阅/ }).click()
 await expect(page.getByRole('heading', { name: '我的订阅', exact: true })).toBeVisible()
 await expect(page.getByText('订阅未启用', { exact: true })).toBeVisible()
 const firstResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/me/subscription/rotate') && r.request().method() === 'POST')
 await page.getByRole('button', { name: '生成订阅链接', exact: true }).click()
 const first = await (await firstResponse).json()
 await expect(page.getByRole('textbox', { name: '订阅链接', exact: true })).toHaveValue(first.urls.clash)
 const empty = await page.request.get(first.urls.uri)
 expect(empty.status()).toBe(200)
 expect((await empty.text()).trim()).toBe('')
 // The URL is intentionally absent after this component unmounts.
 await navigation.getByRole('button', { name: /我的概览/ }).click()
 await navigation.getByRole('button', { name: /我的订阅/ }).click()
 await expect(page.getByText('订阅已启用', { exact: true })).toBeVisible()
 await expect(page.getByRole('textbox', { name: '订阅链接', exact: true })).toHaveCount(0)
 page.once('dialog', dialog => dialog.accept())
 const secondResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/me/subscription/rotate') && r.request().method() === 'POST')
 await page.getByRole('button', { name: '重新生成订阅链接', exact: true }).click()
 const second = await (await secondResponse).json()
 await expect(page.getByRole('textbox', { name: '订阅链接', exact: true })).toHaveValue(second.urls.clash)
 expect(second.urls.uri).not.toBe(first.urls.uri)
 expect([401, 404]).toContain((await page.request.get(first.urls.uri)).status())
 expect((await page.request.get(second.urls.uri)).status()).toBe(200)
 page.once('dialog', dialog => dialog.accept())
 await page.getByRole('button', { name: '撤销订阅链接', exact: true }).click()
 await expect(page.getByText('订阅未启用', { exact: true })).toBeVisible()
 await expect(page.getByRole('textbox', { name: '订阅链接', exact: true })).toHaveCount(0)
 expect([401, 404]).toContain((await page.request.get(second.urls.uri)).status())
 page.once('dialog', dialog => dialog.accept())
 await page.getByRole('button', { name: '重置代理凭据', exact: true }).click()
 await expect(page.getByRole('status').filter({ hasText: '代理凭据已重置' })).toBeVisible()
 await page.screenshot({ path: 'test-results/subscription-manager.png', fullPage: true })
 await page.getByRole('button', { name: '退出', exact: true }).click()
 await expect(navigation.getByRole('button', { name: /我的订阅/ })).toHaveCount(0)
})
